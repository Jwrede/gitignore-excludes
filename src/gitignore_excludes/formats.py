"""Write absolute paths as exclude-file lines for each backup tool.

Each line must match exactly one path. Both restic and borg strip whitespace from both ends of a
line and skip lines that start with `#`; the paths are absolute, so only trailing whitespace needs
care. A newline cannot appear inside a line, so it becomes a one-character wildcard.
"""

from __future__ import annotations

_TRAILING_WS = " \t\r\v\f"


def _trailing_ws_split(path: str) -> tuple[str, str]:
    stripped = path.rstrip(_TRAILING_WS)
    return stripped, path[len(stripped) :]


def restic_line(path: str) -> str:
    """restic --exclude-file: Go filepath.Match per path component, `\\` escapes, `$` expands env vars."""
    body, tail = _trailing_ws_split(path)
    out = []
    for ch in body:
        if ch in "\\*?[":
            out.append("\\" + ch)
        elif ch == "$":
            out.append("$$")
        elif ch == "\n":
            out.append("?")
        else:
            out.append(ch)
    out += [f"[{ch}]" for ch in tail]
    return "".join(out)


def _fnmatch_escape(text: str) -> str:
    out = []
    for ch in text:
        if ch in "*?[":
            out.append(f"[{ch}]")
        elif ch == "\n":
            out.append("?")
        else:
            out.append(ch)
    return "".join(out)


def borg_line(path: str) -> str:
    """borg --exclude-from: `pp:` (literal path prefix) where possible, escaped `fm:` otherwise."""
    body, tail = _trailing_ws_split(path)
    if not tail and "\n" not in path:
        return "pp:" + path
    return "fm:" + _fnmatch_escape(body) + "".join(f"[{ch}]" for ch in tail)


HEADER = "# generated by gitignore-excludes; regenerate before each backup"

FORMATS = {"restic": restic_line, "borg": borg_line}


def render(paths: list[str], fmt: str, null: bool = False) -> str:
    if fmt == "plain":
        sep = "\0" if null else "\n"
        return "".join(p + sep for p in paths)
    line = FORMATS[fmt]
    return HEADER + "\n" + "".join(line(p) + "\n" for p in paths)
